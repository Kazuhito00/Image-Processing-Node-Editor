"""
Sources of the nvinfer bbox parser library shipped with every generated project.

DeepStream has no built-in parser for the raw tensors of the ONNX models
CvStudio runs (Ultralytics YOLO11/YOLOv8 and YOLOX/FreeYOLO), so the project
carries its own: a dependency-free C++ file compiled against the DeepStream
SDK headers (in the Docker image, or with `make parser` on a native install).

Kept as Python strings so they are available in frozen CvStudio builds.
"""

PARSER_SOURCE_NAME = "nvdsparsebbox_cvstudio.cpp"

PARSER_SOURCE = r"""/*
 * nvinfer bounding-box parsers for the ONNX models exported by CvStudio.
 * Generated by CvStudio DeepStream Engine.
 *
 *   NvDsInferParseCvStudioYolo   Ultralytics YOLO11 / YOLOv8 / YOLOv5u detect
 *                                head: one tensor [4 + C, N] (or [N, 4 + C])
 *                                holding cx, cy, w, h and C class scores.
 *   NvDsInferParseCvStudioYoloX  YOLOX / FreeYOLO: one tensor [N, 5 + C]
 *                                holding cx, cy, w, h, objectness and C class
 *                                scores, with boxes still relative to the
 *                                stride 8/16/32 grids.
 *
 * Boxes are returned in network-input pixels; nvinfer rescales them to the
 * frame and applies NMS (cluster-mode=2).
 */

#include <algorithm>
#include <cmath>
#include <iostream>
#include <vector>

#include "nvdsinfer_custom_impl.h"

extern "C" bool NvDsInferParseCvStudioYolo(
    std::vector<NvDsInferLayerInfo> const &outputLayersInfo,
    NvDsInferNetworkInfo const &networkInfo,
    NvDsInferParseDetectionParams const &detectionParams,
    std::vector<NvDsInferObjectDetectionInfo> &objectList);

extern "C" bool NvDsInferParseCvStudioYoloX(
    std::vector<NvDsInferLayerInfo> const &outputLayersInfo,
    NvDsInferNetworkInfo const &networkInfo,
    NvDsInferParseDetectionParams const &detectionParams,
    std::vector<NvDsInferObjectDetectionInfo> &objectList);

namespace {

/* View over a 2-D output tensor, whichever axis holds the attributes. */
struct Tensor2D {
  const float *data = nullptr;
  unsigned int numBoxes = 0;
  unsigned int numAttrs = 0;
  bool attrsFirst = false; /* true: [attrs, boxes], false: [boxes, attrs] */

  float at(unsigned int box, unsigned int attr) const {
    return attrsFirst ? data[attr * numBoxes + box] : data[box * numAttrs + attr];
  }
};

/*
 * Wraps the single output layer. `fixedAttrs` is the number of non-class
 * attributes (4 for YOLO, 5 for YOLOX); the attribute axis is the one that
 * matches the configured class count, else the smaller one.
 */
bool makeTensor(std::vector<NvDsInferLayerInfo> const &layers,
                NvDsInferParseDetectionParams const &params,
                unsigned int fixedAttrs, const char *parser, Tensor2D &out) {
  if (layers.size() != 1) {
    std::cerr << parser << ": expected 1 output layer, got " << layers.size()
              << std::endl;
    return false;
  }
  const NvDsInferLayerInfo &layer = layers[0];
  if (layer.dataType != FLOAT || layer.buffer == nullptr) {
    std::cerr << parser << ": output layer must be a FLOAT tensor" << std::endl;
    return false;
  }

  /* Drop leading singleton dimensions ([1, 84, 8400] -> [84, 8400]). */
  const NvDsInferDims &dims = layer.inferDims;
  unsigned int first = 0;
  while (dims.numDims - first > 2 && dims.d[first] == 1) {
    ++first;
  }
  if (dims.numDims - first != 2) {
    std::cerr << parser << ": expected a 2-D output tensor, got "
              << dims.numDims << " dimensions" << std::endl;
    return false;
  }
  const unsigned int d0 = dims.d[first];
  const unsigned int d1 = dims.d[first + 1];
  const unsigned int expected = params.numClassesConfigured + fixedAttrs;

  if (d0 == expected && d1 != expected) {
    out.attrsFirst = true;
  } else if (d1 == expected) {
    out.attrsFirst = false;
  } else {
    out.attrsFirst = d0 < d1;
  }
  out.numAttrs = out.attrsFirst ? d0 : d1;
  out.numBoxes = out.attrsFirst ? d1 : d0;
  out.data = static_cast<const float *>(layer.buffer);

  if (out.numAttrs <= fixedAttrs) {
    std::cerr << parser << ": output tensor has " << out.numAttrs
              << " attributes per box, need more than " << fixedAttrs
              << std::endl;
    return false;
  }
  return true;
}

float classThreshold(NvDsInferParseDetectionParams const &params,
                     unsigned int classId) {
  if (classId < params.perClassPreclusterThreshold.size()) {
    return params.perClassPreclusterThreshold[classId];
  }
  return 0.0f;
}

void addObject(float cx, float cy, float w, float h, float score,
               unsigned int classId, NvDsInferNetworkInfo const &networkInfo,
               std::vector<NvDsInferObjectDetectionInfo> &objectList) {
  const float netW = static_cast<float>(networkInfo.width);
  const float netH = static_cast<float>(networkInfo.height);
  const float x1 = std::min(std::max(cx - w / 2.0f, 0.0f), netW);
  const float y1 = std::min(std::max(cy - h / 2.0f, 0.0f), netH);
  const float x2 = std::min(std::max(cx + w / 2.0f, 0.0f), netW);
  const float y2 = std::min(std::max(cy + h / 2.0f, 0.0f), netH);
  if (!(x2 - x1 >= 1.0f) || !(y2 - y1 >= 1.0f)) {
    return;
  }
  NvDsInferObjectDetectionInfo object{};
  object.classId = classId;
  object.left = x1;
  object.top = y1;
  object.width = x2 - x1;
  object.height = y2 - y1;
  object.detectionConfidence = score;
  objectList.push_back(object);
}

}  // namespace

extern "C" bool NvDsInferParseCvStudioYolo(
    std::vector<NvDsInferLayerInfo> const &outputLayersInfo,
    NvDsInferNetworkInfo const &networkInfo,
    NvDsInferParseDetectionParams const &detectionParams,
    std::vector<NvDsInferObjectDetectionInfo> &objectList) {
  Tensor2D t;
  if (!makeTensor(outputLayersInfo, detectionParams, 4,
                  "NvDsInferParseCvStudioYolo", t)) {
    return false;
  }
  const unsigned int numClasses = t.numAttrs - 4;

  for (unsigned int b = 0; b < t.numBoxes; ++b) {
    unsigned int bestClass = 0;
    float bestScore = t.at(b, 4);
    for (unsigned int c = 1; c < numClasses; ++c) {
      const float score = t.at(b, 4 + c);
      if (score > bestScore) {
        bestScore = score;
        bestClass = c;
      }
    }
    if (!(bestScore >= classThreshold(detectionParams, bestClass))) {
      continue;
    }
    addObject(t.at(b, 0), t.at(b, 1), t.at(b, 2), t.at(b, 3), bestScore,
              bestClass, networkInfo, objectList);
  }
  return true;
}

extern "C" bool NvDsInferParseCvStudioYoloX(
    std::vector<NvDsInferLayerInfo> const &outputLayersInfo,
    NvDsInferNetworkInfo const &networkInfo,
    NvDsInferParseDetectionParams const &detectionParams,
    std::vector<NvDsInferObjectDetectionInfo> &objectList) {
  Tensor2D t;
  if (!makeTensor(outputLayersInfo, detectionParams, 5,
                  "NvDsInferParseCvStudioYoloX", t)) {
    return false;
  }
  const unsigned int numClasses = t.numAttrs - 5;

  /* Grid cell and stride of every box, in the order YOLOX emits them. */
  static const unsigned int kStrides[] = {8, 16, 32};
  std::vector<float> gridX, gridY, stride;
  gridX.reserve(t.numBoxes);
  gridY.reserve(t.numBoxes);
  stride.reserve(t.numBoxes);
  for (unsigned int s : kStrides) {
    const unsigned int cellsX = networkInfo.width / s;
    const unsigned int cellsY = networkInfo.height / s;
    for (unsigned int y = 0; y < cellsY; ++y) {
      for (unsigned int x = 0; x < cellsX; ++x) {
        gridX.push_back(static_cast<float>(x));
        gridY.push_back(static_cast<float>(y));
        stride.push_back(static_cast<float>(s));
      }
    }
  }
  /* A model exported with the decoding baked in has another box count. */
  const bool decode = gridX.size() == t.numBoxes;

  for (unsigned int b = 0; b < t.numBoxes; ++b) {
    const float objectness = t.at(b, 4);
    unsigned int bestClass = 0;
    float bestScore = t.at(b, 5);
    for (unsigned int c = 1; c < numClasses; ++c) {
      const float score = t.at(b, 5 + c);
      if (score > bestScore) {
        bestScore = score;
        bestClass = c;
      }
    }
    bestScore *= objectness;
    if (!(bestScore >= classThreshold(detectionParams, bestClass))) {
      continue;
    }

    float cx = t.at(b, 0);
    float cy = t.at(b, 1);
    float w = t.at(b, 2);
    float h = t.at(b, 3);
    if (decode) {
      cx = (cx + gridX[b]) * stride[b];
      cy = (cy + gridY[b]) * stride[b];
      w = std::exp(w) * stride[b];
      h = std::exp(h) * stride[b];
    }
    addObject(cx, cy, w, h, bestScore, bestClass, networkInfo, objectList);
  }
  return true;
}

CHECK_CUSTOM_PARSE_FUNC_PROTOTYPE(NvDsInferParseCvStudioYolo);
CHECK_CUSTOM_PARSE_FUNC_PROTOTYPE(NvDsInferParseCvStudioYoloX);
"""

