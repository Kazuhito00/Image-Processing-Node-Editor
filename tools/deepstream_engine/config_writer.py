"""
DeepStream configuration file writer.

Writes the deepstream-app configuration, one nvinfer configuration per model
and the label files of a DeepStreamPipeline.
"""

from __future__ import annotations

from pathlib import Path

from tools.deepstream_engine.mappers.inference_mapper import InferenceConfig
from tools.deepstream_engine.pipeline_builder import DeepStreamPipeline

MAIN_CONFIG = "deepstream_app_config.txt"
PGIE_CONFIG = "config_pgie.txt"


def sgie_config_name(index: int) -> str:
    return f"config_sgie_{index}.txt"


def write_project(pipeline: DeepStreamPipeline, output_dir: str | Path) -> list[str]:
    """
    Write all DeepStream configuration files to the output directory.

    Returns a list of generated file paths (relative to output_dir).
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    generated = [_write_main_config(pipeline, output_dir)]

    if pipeline.primary_gie:
        generated.append(_write_infer_config(pipeline.primary_gie, output_dir, PGIE_CONFIG))
    for i, sgie in enumerate(pipeline.secondary_gies):
        generated.append(_write_infer_config(sgie, output_dir, sgie_config_name(i)))

    for gie in pipeline.gies:
        if gie.labels_file:
            generated.append(_write_labels_file(gie, output_dir))

    return generated


def _write_main_config(pipeline: DeepStreamPipeline, output_dir: Path) -> str:
    """Write the deepstream-app configuration."""
    gpu = str(pipeline.profile.gpu_id)
    memtype = str(pipeline.profile.nvbuf_memory_type)
    groups: list[tuple[str, dict[str, str]]] = [
        ("application", {
            "enable-perf-measurement": "1",
            "perf-measurement-interval-sec": "5",
        }),
        ("tiled-display", {
            "enable": "1" if pipeline.tiler_config else "0",
            **pipeline.tiler_config,
        }),
    ]

    for i, source in enumerate(pipeline.sources):
        groups.append((f"source{i}", {"enable": "1", **source.config_entries}))

    groups.append(("streammux", dict(pipeline.streammux_config)))

    pgie = pipeline.primary_gie
    if pgie:
        groups.append(("primary-gie", {
            "enable": "1",
            "gpu-id": gpu,
            "gie-unique-id": str(pgie.gie_id),
            "batch-size": str(pgie.batch_size),
            "interval": str(pgie.interval),
            "nvbuf-memory-type": memtype,
            "config-file": PGIE_CONFIG,
        }))

    if pipeline.tracker:
        groups.append(("tracker", {"enable": "1", **pipeline.tracker.config_entries}))

    for i, sgie in enumerate(pipeline.secondary_gies):
        groups.append((f"secondary-gie{i}", {
            "enable": "1",
            "gpu-id": gpu,
            "gie-unique-id": str(sgie.gie_id),
            "operate-on-gie-id": str(sgie.operate_on_gie_id),
            "batch-size": str(sgie.batch_size),
            "nvbuf-memory-type": memtype,
            "config-file": sgie_config_name(i),
        }))

    groups.append(("osd", {
        "enable": "1" if pipeline.osd_enabled else "0",
        "gpu-id": gpu,
        "border-width": "2",
        "text-size": "15",
        "text-color": "1;1;1;1;",
        "text-bg-color": "0.3;0.3;0.3;1;",
        "font": "Serif",
        "show-clock": "0",
        "nvbuf-memory-type": memtype,
    }))

    for i, sink in enumerate(pipeline.sinks):
        groups.append((f"sink{i}", {"enable": "1", **sink.config_entries}))

    groups.append(("tests", {"file-loop": "1" if pipeline.file_loop else "0"}))

    lines = [
        f"# deepstream-app configuration for '{pipeline.name}'",
        "# Generated by CvStudio DeepStream Engine",
        "",
    ]
    for name, entries in groups:
        lines.append(f"[{name}]")
        lines.extend(f"{key}={value}" for key, value in entries.items())
        lines.append("")

    (output_dir / MAIN_CONFIG).write_text("\n".join(lines), encoding="utf-8")
    return MAIN_CONFIG


def _write_infer_config(config: InferenceConfig, output_dir: Path, filename: str) -> str:
    """Write an nvinfer configuration file."""
    lines = [
        f"# nvinfer configuration for '{config.model_name}' ({config.node_tag})",
        "# Generated by CvStudio DeepStream Engine",
        "",
    ]
    for section, entries in config.config_entries.items():
        lines.append(section)
        lines.extend(f"{key}={value}" for key, value in entries.items())
        lines.append("")

    (output_dir / filename).write_text("\n".join(lines), encoding="utf-8")
    return filename


def _write_labels_file(config: InferenceConfig, output_dir: Path) -> str:
    """Write the label file in the layout nvinfer expects for the network type."""
    names = [name.replace(";", ",").replace("\n", " ") for name in config.class_names]
    if config.network_type == 1:
        # Classifier: one line per output layer, labels separated by ';'.
        content = ";".join(names) + "\n"
    else:
        # Detector: one label per line, in class-id order.
        content = "\n".join(names) + "\n"
    (output_dir / config.labels_file).write_text(content, encoding="utf-8")
    return config.labels_file
