"""
Project scaffolding generator.

Creates everything around the DeepStream configuration files so the project
runs as-is on a machine with an NVIDIA GPU:
  - Dockerfile / docker-compose.yml (NVIDIA DeepStream base image)
  - nvdsinfer_custom_impl_cvstudio/ (bbox parser library sources)
  - Makefile, run.sh (native launcher), README.md
  - models/ and output/ directories
"""

from __future__ import annotations

import re
from pathlib import Path

from tools.deepstream_engine.config_writer import MAIN_CONFIG
from tools.deepstream_engine.mappers.inference_mapper import PARSER_LIB, PARSER_LIB_DIR
from tools.deepstream_engine.mappers.sink_mapper import RTSP_MOUNT
from tools.deepstream_engine.pipeline_builder import DeepStreamPipeline
from tools.deepstream_engine.templates.bbox_parser import (
    PARSER_MAKEFILE,
    PARSER_SOURCE,
    PARSER_SOURCE_NAME,
)

DEEPSTREAM_IMAGE = "nvcr.io/nvidia/deepstream:7.1-triton-multiarch"


def generate_scaffold(pipeline: DeepStreamPipeline, output_dir: str | Path) -> list[str]:
    """Generate all scaffolding files for the DeepStream project."""
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    (output_dir / "models").mkdir(exist_ok=True)
    (output_dir / "output").mkdir(exist_ok=True)

    generated = []
    if pipeline.uses_custom_parser:
        generated.extend(_write_parser_library(output_dir))
    generated.append(_write_dockerfile(pipeline, output_dir))
    generated.append(_write(output_dir, ".dockerignore", _DOCKERIGNORE))
    generated.append(_write_docker_compose(pipeline, output_dir))
    generated.append(_write_makefile(pipeline, output_dir))
    generated.append(_write_run_script(pipeline, output_dir))
    generated.append(_write_readme(pipeline, output_dir))
    generated.append(_write(output_dir, ".gitignore", _GITIGNORE))
    return generated


def docker_name(name: str) -> str:
    """Project name usable as a Docker image / container name."""
    cleaned = re.sub(r"[^a-z0-9_.-]+", "-", name.lower()).strip("-._")
    return cleaned or "cvstudio-deepstream"


def _write(output_dir: Path, relative: str, content: str, executable: bool = False) -> str:
    path = output_dir / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    if executable:
        path.chmod(0o755)
    return relative


def _write_parser_library(output_dir: Path) -> list[str]:
    return [
        _write(output_dir, f"{PARSER_LIB_DIR}/{PARSER_SOURCE_NAME}", PARSER_SOURCE),
        _write(output_dir, f"{PARSER_LIB_DIR}/Makefile", PARSER_MAKEFILE),
    ]


def _write_dockerfile(pipeline: DeepStreamPipeline, output_dir: Path) -> str:
    profile = pipeline.profile
    parser_steps = ""
    if pipeline.uses_custom_parser:
        parser_steps = f"""
# Build the bbox parser library for the CvStudio models
RUN command -v g++ >/dev/null && command -v make >/dev/null || \\
    (apt-get update && apt-get install -y --no-install-recommends g++ make \\
     && rm -rf /var/lib/apt/lists/*)
COPY {PARSER_LIB_DIR}/ ./{PARSER_LIB_DIR}/
RUN make -C {PARSER_LIB_DIR}
"""

    content = f"""# ==============================================================================
# DeepStream production image for '{pipeline.name}'
# Generated by CvStudio DeepStream Engine
# Target: {profile.name} ({profile.vram_gb}GB VRAM, {profile.system_ram_gb}GB RAM)
# ==============================================================================

# Override to target another DeepStream release, e.g.
#   docker compose build --build-arg DEEPSTREAM_IMAGE=nvcr.io/nvidia/deepstream:<tag>
ARG DEEPSTREAM_IMAGE={DEEPSTREAM_IMAGE}
FROM ${{DEEPSTREAM_IMAGE}}

ENV DEBIAN_FRONTEND=noninteractive
ENV CUDA_MODULE_LOADING=LAZY

# Codecs and RTSP components NVIDIA leaves out of the base image
RUN if [ -x /opt/nvidia/deepstream/deepstream/user_additional_install.sh ]; then \\
        /opt/nvidia/deepstream/deepstream/user_additional_install.sh; \\
    fi

WORKDIR /app
{parser_steps}
# Pipeline configuration. models/ and output/ are mounted at run time so the
# TensorRT engines built on first start are kept on the host.
COPY *.txt ./
RUN mkdir -p models output

ENTRYPOINT ["deepstream-app"]
CMD ["-c", "{MAIN_CONFIG}"]
"""
    return _write(output_dir, "Dockerfile", content)


def _write_docker_compose(pipeline: DeepStreamPipeline, output_dir: Path) -> str:
    name = docker_name(pipeline.name)
    has_display = any(sink.sink_type == "egl" for sink in pipeline.sinks)

    volumes = ["./models:/app/models", "./output:/app/output"]
    # File sources keep their host path inside the container.
    for directory in sorted({str(s.local_path.parent) for s in pipeline.sources if s.local_path}):
        volumes.append(f"{directory}:{directory}:ro")
    if has_display:
        volumes.append("/tmp/.X11-unix:/tmp/.X11-unix:rw")

    environment = [
        "NVIDIA_VISIBLE_DEVICES=all",
        "NVIDIA_DRIVER_CAPABILITIES=all",
    ]
    if has_display:
        environment.append("DISPLAY=${DISPLAY:-:0}")

    devices = sorted({s.device for s in pipeline.sources if s.device})

    lines = [
        "# Docker Compose deployment for the DeepStream pipeline",
        "# Generated by CvStudio DeepStream Engine",
        "# Requires the NVIDIA Container Toolkit (nvidia runtime).",
        "",
        "services:",
        "  deepstream:",
        "    build: .",
        f"    image: cvstudio-deepstream-{name}",
        f"    container_name: {name}",
        "    runtime: nvidia",
        "    network_mode: host",
        "    ipc: host",
        # A file pipeline ends at end-of-stream; only live pipelines restart.
        f"    restart: {'unless-stopped' if pipeline.is_live else chr(34) + 'no' + chr(34)}",
        "    environment:",
        *[f"      - {entry}" for entry in environment],
        "    volumes:",
        *[f"      - {_yaml_quote(entry)}" for entry in volumes],
    ]
    if devices:
        lines.append("    devices:")
        lines.extend(f"      - {device}:{device}" for device in devices)

    return _write(output_dir, "docker-compose.yml", "\n".join(lines) + "\n")


def _yaml_quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _write_makefile(pipeline: DeepStreamPipeline, output_dir: Path) -> str:
    parser_target = ""
    if pipeline.uses_custom_parser:
        parser_target = f"""
# Build the bbox parser library (native run; done by the Dockerfile otherwise)
parser:
\t$(MAKE) -C {PARSER_LIB_DIR}
"""
    content = f"""# ==============================================================================
# DeepStream project '{pipeline.name}'
# Generated by CvStudio DeepStream Engine
# ==============================================================================

.PHONY: build run run-interactive stop logs parser run-native clean

# Build the Docker image
build:
\tdocker compose build

# Run the pipeline in the background
run:
\tdocker compose up -d --build
\t@echo "Pipeline started. Use 'make logs' to follow it."

# Run in the foreground
run-interactive:
\tdocker compose up --build

stop:
\tdocker compose down

logs:
\tdocker compose logs -f
{parser_target}
# Run without Docker (needs the DeepStream SDK installed on this machine)
run-native:
\t./run.sh

# Remove TensorRT engines and recordings
clean:
\trm -f models/*.engine output/*
"""
    return _write(output_dir, "Makefile", content)


def _write_run_script(pipeline: DeepStreamPipeline, output_dir: Path) -> str:
    build_parser = ""
    if pipeline.uses_custom_parser:
        build_parser = f"""
if [ ! -f "{PARSER_LIB}" ]; then
    echo "[INFO] Building the bbox parser library..."
    make -C "{PARSER_LIB_DIR}"
fi
"""
    content = f"""#!/bin/bash
# ==============================================================================
# Native launcher for the DeepStream pipeline '{pipeline.name}'
# Generated by CvStudio DeepStream Engine
# Needs the NVIDIA DeepStream SDK installed on this machine.
# ==============================================================================

set -euo pipefail

cd "$(dirname "${{BASH_SOURCE[0]}}")"

if ! command -v nvidia-smi >/dev/null 2>&1 || ! nvidia-smi >/dev/null 2>&1; then
    echo "[ERROR] No working NVIDIA driver found (nvidia-smi failed)." >&2
    exit 1
fi
if ! command -v deepstream-app >/dev/null 2>&1; then
    echo "[ERROR] deepstream-app not found. Install the DeepStream SDK or use 'make run' (Docker)." >&2
    exit 1
fi
{build_parser}
for onnx_file in {' '.join(f'"{gie.onnx_path}"' for gie in pipeline.gies) or '""'}; do
    if [ -n "$onnx_file" ] && [ ! -f "$onnx_file" ]; then
        echo "[ERROR] Missing model: $onnx_file" >&2
        exit 1
    fi
done

mkdir -p output
echo "[INFO] Starting DeepStream pipeline '{pipeline.name}'."
echo "[INFO] The first start builds the TensorRT engines; this takes a few minutes."
exec deepstream-app -c {MAIN_CONFIG} "$@"
"""
    return _write(output_dir, "run.sh", content, executable=True)


def _write_readme(pipeline: DeepStreamPipeline, output_dir: Path) -> str:
    profile = pipeline.profile

    sources = "\n".join(
        f"- Source {s.source_id} ({s.node_tag}): `{s.uri or s.device}`"
        for s in pipeline.sources
    )

    inference = []
    for gie in pipeline.gies:
        role = "Primary" if gie.gie_type == "primary" else "Secondary"
        kind = "detector" if gie.network_type == 0 else "classifier"
        size = f", {gie.input_width}x{gie.input_height}" if gie.input_width else ""
        state = "copied" if gie.source_model_path else "**missing, copy it there**"
        inference.append(
            f"- {role} {kind}: **{gie.model_name}** ({gie.output_format}{size}, "
            f"batch {gie.batch_size}) → `{gie.onnx_path}` ({state})"
        )
    inference_text = "\n".join(inference) or "- None (video pass-through)"

    if pipeline.tracker:
        tracker = (
            f"- {pipeline.tracker.algorithm} (NvMultiObjectTracker), mapped from "
            f"CvStudio's {pipeline.tracker.tracker_name}"
        )
    else:
        tracker = "- None"

    sinks = []
    for sink in pipeline.sinks:
        if sink.sink_type == "file":
            sinks.append(f"- Sink {sink.sink_id}: MP4 recording → `{sink.output_path}`")
        elif sink.sink_type == "rtsp":
            sinks.append(
                f"- Sink {sink.sink_id}: RTSP stream → "
                f"`rtsp://<host>:{sink.rtsp_port}{RTSP_MOUNT}` "
                f"(open it with VLC or `ffplay`)"
            )
        elif sink.sink_type == "egl":
            sinks.append(f"- Sink {sink.sink_id}: on-screen window (needs an X display)")
        else:
            sinks.append(f"- Sink {sink.sink_id}: none (metadata only)")

    notes = [f"- {warning}" for warning in pipeline.warnings]
    if pipeline.ignored_nodes:
        notes.append(
            "- CvStudio nodes without a DeepStream equivalent were left out: "
            + ", ".join(f"`{n}`" for n in pipeline.ignored_nodes)
        )
    notes_text = "\n".join(notes) or "- None: every node was converted."

    precision = "INT8" if profile.int8_enabled else "FP16" if profile.fp16_enabled else "FP32"
    parser_tree = (
        f"├── {PARSER_LIB_DIR}/   # bbox parser library sources\n"
        if pipeline.uses_custom_parser
        else ""
    )

    content = f"""# {pipeline.name}

NVIDIA DeepStream pipeline generated from a CvStudio project, tuned for
**{profile.name}** ({profile.vram_gb} GB VRAM, {precision}).

```
sources → nvstreammux → nvinfer (PGIE) → nvtracker → nvinfer (SGIE) → tiler → OSD → sinks
```

Decoding, inference (TensorRT), tracking, overlay and encoding all run on the GPU.

## Pipeline

### Sources
{sources}

### Inference
{inference_text}

### Tracker
{tracker}

### Outputs
{chr(10).join(sinks)}

## Conversion notes

Review these before going to production:

{notes_text}

## Run with Docker (recommended)

Requirements: NVIDIA driver, Docker and the
[NVIDIA Container Toolkit](https://docs.nvidia.com/datacenter/cloud-native/container-toolkit/latest/install-guide.html).

```bash
make run      # build the image and start the pipeline
make logs     # follow the output (FPS is printed every 5 s)
make stop
```

The first start builds the TensorRT engines from the ONNX files in `models/`
(a few minutes per model). They are cached in `models/` for the next starts and
must be rebuilt (`make clean`) when the GPU or the DeepStream version changes.

## Run without Docker

Requires the NVIDIA DeepStream SDK 7.x on the machine (x86 GPU server or Jetson).

```bash
./run.sh
```

## Files

```
{pipeline.name}/
├── {MAIN_CONFIG}   # sources, streammux, tracker, OSD, sinks
├── config_pgie.txt             # nvinfer config of the primary model
├── config_sgie_*.txt           # nvinfer configs of the secondary models
├── labels_gie*.txt             # class labels
{parser_tree}├── models/                     # ONNX models and cached TensorRT engines
├── output/                     # recordings
├── Dockerfile, docker-compose.yml, Makefile
└── run.sh                      # native launcher
```

## Tuning

| Setting | Where | Value |
|---------|-------|-------|
| TensorRT precision | `network-mode` in `config_*gie*.txt` | {precision} |
| Detection threshold | `pre-cluster-threshold` in `config_pgie.txt` | from CvStudio |
| Skip frames between inferences | `interval` in `[primary-gie]` | {profile.infer_interval - 1} |
| Stream resolution | `[streammux]` width/height | 1920x1080 |

- **Out of GPU memory**: lower `batch-size`, or raise `interval`.
- **RTSP source drops**: raise `latency` in the `[sourceN]` group.
- **More cameras**: duplicate a `[sourceN]` group and raise `batch-size` in
  `[streammux]`; batched inference needs an ONNX exported with a dynamic batch.
"""
    return _write(output_dir, "README.md", content)


